#!/usr/bin/env bash
# One-time setup of Aurora on a single free server (Oracle Cloud Always Free, Ubuntu 24.04). See docs/FREE_HOSTING.md.
#
# Run from the repository folder on the server:
#   bash deploy/oracle-free/setup.sh
# It asks for the web address and two e-mail addresses, then installs Docker, opens ports 80 and 443, generates
# every secret on this server (they never leave it), builds and starts Aurora behind HTTPS, creates the first
# admin account and schedules a nightly database backup. Running it again is safe: existing secrets are kept.
set -euo pipefail

cd "$(dirname "$0")/../.."
ROOT=$(pwd)
COMPOSE=(sudo docker compose -f docker-compose.yml -f deploy/oracle-free/compose.https.yml)

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ask() { # ask VAR "question" : keeps an existing value from the environment
  local var=$1 q=$2
  if [ -z "${!var:-}" ]; then read -r -p "$q " "$var"; fi
  [ -n "${!var}" ] || { echo "No value given for $var" >&2; exit 1; }
}
rand() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-"${1:-40}"; }

if [ -f .env ]; then
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
  say "Found an existing .env; keeping its secrets."
fi

ask AURORA_DOMAIN "Web address for Aurora (for example yourname.duckdns.org):"
AURORA_DOMAIN=${AURORA_DOMAIN#https://}; AURORA_DOMAIN=${AURORA_DOMAIN#http://}; AURORA_DOMAIN=${AURORA_DOMAIN%%/*}
ask ACME_EMAIL "E-mail for HTTPS certificate notices:"
ask BOOTSTRAP_ADMIN_EMAIL "E-mail for the first Aurora admin account:"

say "1/7 Installing Docker"
if ! command -v docker >/dev/null || ! sudo docker compose version >/dev/null 2>&1; then
  sudo apt-get update -y
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y docker.io docker-compose-v2 openssl git cron
  sudo systemctl enable --now docker
fi

say "2/7 Adding swap (helps the first build on a small server)"
if [ "$(swapon --show --noheadings | wc -l)" -eq 0 ]; then
  sudo fallocate -l 4G /swapfile && sudo chmod 600 /swapfile && sudo mkswap /swapfile >/dev/null && sudo swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
fi

say "3/7 Opening ports 80 and 443 in the server firewall"
# Oracle's Ubuntu images reject everything but SSH in iptables, in addition to the cloud security list.
for rule in "-p tcp --dport 80" "-p tcp --dport 443" "-p udp --dport 443"; do
  # shellcheck disable=SC2086
  sudo iptables -C INPUT $rule -j ACCEPT 2>/dev/null || sudo iptables -I INPUT 1 $rule -j ACCEPT
done
if command -v netfilter-persistent >/dev/null; then sudo netfilter-persistent save >/dev/null; fi

say "4/7 Writing secrets to .env (only on this server)"
if [ ! -f .env ]; then
  umask 077
  cat > .env <<ENV
# Generated by deploy/oracle-free/setup.sh on $(date -u +%F). Never commit or share this file.
ENVIRONMENT=production
AURORA_DOMAIN=$AURORA_DOMAIN
ACME_EMAIL=$ACME_EMAIL
PUBLIC_URL=https://$AURORA_DOMAIN
POSTGRES_PASSWORD=$(rand 40)
APP_DB_PASSWORD=$(rand 40)
SECRET_KEY=$(rand 64)
TOKEN_ENCRYPTION_KEYS=$(openssl rand -base64 32 | tr '+/' '-_')
BOOTSTRAP_ADMIN_EMAIL=$BOOTSTRAP_ADMIN_EMAIL
BOOTSTRAP_ADMIN_PASSWORD=$(rand 18)-Aa7
API_WORKERS=1
# Optional: paste an Anthropic key here for the full assistant, then run deploy/oracle-free/update.sh
ANTHROPIC_API_KEY=
ENV
  umask 022
fi
chmod 600 .env
set -a; . ./.env; set +a

say "5/7 Checking that $AURORA_DOMAIN points to this server"
MY_IP=$(curl -fsS https://api.ipify.org || true)
DNS_IP=$(getent ahostsv4 "$AURORA_DOMAIN" | awk 'NR==1{print $1}' || true)
if [ -n "$MY_IP" ] && [ "$MY_IP" != "$DNS_IP" ]; then
  echo "Warning: $AURORA_DOMAIN points to '${DNS_IP:-nothing}', but this server's public address is $MY_IP."
  echo "Set the address on DuckDNS (or your DNS) to $MY_IP. HTTPS will start working a minute after it matches."
fi

say "6/7 Building and starting Aurora (the first build takes 15-30 minutes)"
"${COMPOSE[@]}" build
"${COMPOSE[@]}" up -d
# `run` waits for the database migrations to finish first.
"${COMPOSE[@]}" run --rm api python -m app.cli bootstrap

say "7/7 Scheduling a nightly database backup (kept 7 days in /var/backups/aurora)"
sudo mkdir -p /var/backups/aurora && sudo chmod 700 /var/backups/aurora
sudo tee /etc/cron.d/aurora-backup >/dev/null <<CRON
# Nightly Aurora database backup (deploy/oracle-free/setup.sh)
30 2 * * * root cd $ROOT && docker compose -f docker-compose.yml -f deploy/oracle-free/compose.https.yml exec -T db pg_dump -U aurora -Fc aurora > /var/backups/aurora/aurora-\$(date +\%F).dump && find /var/backups/aurora -name 'aurora-*.dump' -mtime +7 -delete
CRON

say "Done."
cat <<DONE
Open:      https://$AURORA_DOMAIN
Admin:     $BOOTSTRAP_ADMIN_EMAIL
Password:  $BOOTSTRAP_ADMIN_PASSWORD   (change it after signing in; it is also in .env)

If the page does not load yet, check that ports 80 and 443 are open in the Oracle security list (docs/FREE_HOSTING.md)
and that the address points to $MY_IP. Logs: sudo docker compose -f docker-compose.yml -f deploy/oracle-free/compose.https.yml logs -f caddy web api
DONE
